import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import process from 'node:process';
import console from 'node:console';
import { resolve } from 'node:path';
import { format, resolveConfig } from 'prettier';
import { z } from 'zod';
import { designTokenSchema, parseDesignTokens } from '../src/design/tokens.ts';

const root = resolve(import.meta.dirname, '..');
const sourcePath = resolve(root, 'design/react-desktop-v2.tokens.json');
const outputPath = resolve(root, 'src/client/styles/design-tokens.css');
const tokens = parseDesignTokens(JSON.parse(readFileSync(sourcePath, 'utf8')));

function declarations(values, prefix, rename = {}) {
  return Object.entries(values).map(([name, value]) => {
    const property = rename[name] ?? `--${prefix}-${name}`;
    return `  ${property}: ${value};`;
  });
}

function theme(name) {
  const values = tokens.theme[name];
  return [
    ...declarations(values, 'color'),
    '  --ink: var(--color-foreground);',
    '  --muted: var(--color-foreground-subtle);',
    '  --line: var(--color-border);',
    '  --surface: var(--color-panel);',
    '  --blue: var(--color-link);',
    '  --blue-dark: var(--color-primary);',
    '  --lavender: var(--color-accent);',
  ];
}

const base = [
  ...declarations(tokens.font, 'font'),
  ...declarations(tokens.typography, 'text', {
    'ui-font-size': '--ui-font-size',
    'line-heading': '--line-heading',
    'line-body': '--line-body',
    'line-compact': '--line-compact',
  }),
  ...declarations(tokens.space, 'space'),
  ...declarations(tokens.radius, 'radius'),
  ...declarations(tokens.control, 'control'),
  ...declarations(tokens.motion, 'motion'),
  ...declarations(tokens.elevation, 'shadow'),
  ...declarations(tokens.layout, 'layout'),
  ...declarations(tokens.icon, 'icon'),
  ...declarations(tokens.border, 'border'),
  ...declarations(tokens.layer, 'layer'),
  ...declarations(tokens.weight, 'weight'),
];

const rawContent = `${[
  '/* Generated by scripts/generate-design-tokens.mjs from design/react-desktop-v2.tokens.json. */',
  '/* Do not edit this file by hand. */',
  '',
  ':root,',
  ":root[data-theme='light'] {",
  '  color-scheme: light;',
  ...base,
  ...theme('light'),
  '}',
  '',
  ":root[data-theme='dark'] {",
  '  color-scheme: dark;',
  ...theme('dark'),
  '}',
  '',
].join('\n')}\n`;
const prettierConfig = (await resolveConfig(outputPath)) ?? {};
const content = await format(rawContent, {
  ...prettierConfig,
  filepath: outputPath,
  parser: 'css',
});

const goName = (name) =>
  name
    .split('-')
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join('');
const goPalette = (theme) =>
  Object.entries(tokens.theme[theme])
    .map(([name, value]) => `\t${goName(name)}: ui.Hex("${value}"),`)
    .join('\n');
const goDimensions = [
  'typography',
  'space',
  'radius',
  'control',
  'layout',
  'icon',
  'border',
]
  .flatMap((group) =>
    Object.entries(tokens[group])
      .filter(([, value]) => value.endsWith('px'))
      .map(
        ([name, value]) =>
          `\t${goName(group)}${goName(name)} = ${parseFloat(value)}`,
      ),
  )
  .join('\n');
const goSource = `// Code generated by scripts/generate-design-tokens.mjs; DO NOT EDIT.
package design

import "github.com/egoist/mygo/ui"

type Palette struct {
${Object.keys(tokens.theme.light)
  .map((name) => `\t${goName(name)} ui.Color`)
  .join('\n')}
}

func Colors(dark bool) Palette {
  if dark { return Palette{
${goPalette('dark')}
  } }
  return Palette{
${goPalette('light')}
  }
}

const (
${goDimensions}
  PressDurationMs = ${parseInt(tokens.motion['press-duration'], 10)}
  SidebarDurationMs = ${parseInt(tokens.motion['sidebar-duration'], 10)}
)
`;
const goContent = execFileSync('gofmt', [], {
  input: goSource,
  encoding: 'utf8',
});
const schemaContent = await format(
  JSON.stringify(z.toJSONSchema(designTokenSchema)),
  { parser: 'json' },
);
const outputs = [
  [outputPath, content],
  [resolve(root, 'desktop/internal/design/tokens_gen.go'), goContent],
  [resolve(root, 'design/tokens.schema.json'), schemaContent],
];
for (const [path, generated] of outputs) {
  if (process.argv.includes('--check')) {
    let current;
    try {
      current = readFileSync(path, 'utf8');
    } catch {
      current = '';
    }
    if (current !== generated) {
      console.error(
        `Generated design artifact is stale: ${path}. Run npm run design:generate.`,
      );
      process.exitCode = 1;
    }
  } else {
    mkdirSync(resolve(path, '..'), { recursive: true });
    writeFileSync(path, generated);
    console.log(`Wrote ${path}`);
  }
}
if (process.argv.includes('--check') && !process.exitCode)
  console.log(
    'CSS, Go and JSON schema are current; both palettes meet contrast requirements.',
  );
